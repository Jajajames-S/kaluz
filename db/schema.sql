create table if not exists conductores (
    id          bigint generated by default as identity primary key,
    dni         varchar(8)   not null unique,
    nombres     varchar(100) not null,
    apellidos   varchar(100) not null,
    telefono    varchar(20)  not null,
    estado      varchar(20)  not null default 'ACTIVO'
                check (estado in ('ACTIVO','INACTIVO','SUSPENDIDO')),
    created_at  timestamptz  not null default now()
);

create table if not exists vehiculos (
    id                    bigint generated by default as identity primary key,
    placa                 varchar(10)  not null unique,
    tipo                  varchar(20)  not null check (tipo in ('TAXI','TURISMO','COMBI')),
    marca                 varchar(60),
    conductor_id          bigint references conductores(id) on delete set null,
    latitud               double precision check (latitud  between -90  and 90),
    longitud              double precision check (longitud between -180 and 180),
    ultima_actualizacion_gps timestamptz,
    created_at            timestamptz not null default now()
);
create index if not exists idx_vehiculos_conductor on vehiculos(conductor_id);

create table if not exists documentos (
    id                 bigint generated by default as identity primary key,
    vehiculo_id        bigint      not null references vehiculos(id) on delete cascade,
    tipo_doc           varchar(30) not null check (tipo_doc in ('SOAT','REVISION_TECNICA')),
    fecha_vencimiento  date        not null,
    estado_doc         varchar(20) not null default 'VIGENTE'
                       check (estado_doc in ('VIGENTE','POR_VENCER','VENCIDO')),
    created_at         timestamptz not null default now()
);
create index if not exists idx_documentos_vencimiento on documentos(fecha_vencimiento);

create table if not exists carreras (
    id               bigint generated by default as identity primary key,
    conductor_id     bigint        not null references conductores(id),
    precio           numeric(10,2) not null check (precio > 0),
    comision_empresa numeric(10,2) not null,            -- precio * 0.05
    estado           varchar(20)   not null default 'COMPLETADA'
                     check (estado in ('PENDIENTE','EN_CURSO','COMPLETADA','CANCELADA')),
    created_at       timestamptz   not null default now()
);
create index if not exists idx_carreras_conductor on carreras(conductor_id);

create table if not exists liquidaciones (
    id                    bigint generated by default as identity primary key,
    conductor_id          bigint        not null references conductores(id),
    comision_acumulada_5  numeric(12,2) not null default 0,
    estado_pago           varchar(20)   not null default 'PENDIENTE'
                          check (estado_pago in ('PENDIENTE','PAGADO')),
    created_at            timestamptz   not null default now(),
    fecha_pago            timestamptz
);
-- Solo una liquidacion PENDIENTE (abierta) por conductor
create unique index if not exists uq_liquidacion_pendiente
    on liquidaciones(conductor_id) where estado_pago = 'PENDIENTE';

-- Seguridad Supabase: bloquea acceso por la Data API publica (anon/authenticated).
-- El backend Spring se conecta con el rol postgres, que ignora RLS.
alter table conductores   enable row level security;
alter table vehiculos     enable row level security;
alter table documentos    enable row level security;
alter table carreras      enable row level security;
alter table liquidaciones enable row level security;
